export const languages = ["system", "en", "zh-CN"];

export function resolveLang(preference, systemLang) {
  if (preference === "en" || preference === "zh-CN") return preference;
  const candidate = (systemLang || "").toLowerCase();
  if (candidate.startsWith("zh")) return "zh-CN";
  return "en";
}

export function translate(lang, key, values) {
  const dictionary = dictionaries[lang] || dictionaries.en;
  let text = dictionary[key] ?? dictionaries.en[key] ?? key;
  if (values) {
    for (const [name, value] of Object.entries(values)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}
